test('⑨ ★ 正文里不许出现会过期的「当前状态数」', () => {
  // ★ 这条判据的存在理由（2026-10-18，第七次修订的家族）：
  //   README 里曾写着「A_k 只有 5 项有数据源」和「34 天，共 50.7 天跨度」——
  //   而这两个数【明天就不再正确】，因为账本每天都在长、数据源随时会补。
  //   ⇒ 判据 ⑦ 只抓 "N/N"，抓不到它们；而这正是它漏掉的那一类。
  //
  // ★ 规则：禁「数字 + 天/项/条/个/次」——那是"当前有几 X"的形态。
  //   允许：日期（2026-08-28）· 代码块里的东西 · 「小时」（历史上的一次间隔，已经固定）
  //   ⇒ 会过期的数应改为【指向能算它的命令】，例如
  //     `node test/audit-timeline.mjs`（时间轴）· `node test/audit-short-deposits.mjs`（引用率）
  const t = read();
  const body = t.replace(/```[\s\S]*?```/g, '');   // 去掉代码块
  const hits = [...body.matchAll(/(\d+)\s*(天|项|条|个|次)/g)]
    .filter(m => !/^\d{4}$/.test(m[1]));           // 排除年份粘连
  assert.equal(hits.length, 0,
    '★ 正文里有会过期的当前状态数「' + (hits[0] && hits[0][0]) + '」—— ' +
    '这类数每天都在变，应改为指向能算出它的命令');
});

test('⑦ 一条可核对的东西：必须给出【能真的跑的命令】，且数字不许手写', () => {
  // ★ 这条判据的两次修订（2026-10-18）：
  //   第一版：要求 README 里必须出现 "221/221" 这样的计数。
  //   ⇒ 而它与我后来写的对账器（要求"数字必须与真实一致"）冲突：
  //     **手写的数字必然过期**，所以"要求手写数字"等于"要求它过期"。
  //   ⇒ 修法：命令必须能跑（可核对），而**数字不许手写** ——
  //     要么指向 CI badge（自动更新），要么由脚本生成。
  //   ★ 这和一个更早的教训同族：判据不许要求"今天成立"的东西（P550-M463）。
  const t = read();
  assert.ok(/npm test/.test(t), '必须给出真的能跑的命令');

  // 只禁【两数相同的】"N/N"（那是最典型的"当前状态"：通过数/总数）
  // ★ 第四次修订（2026-10-18，而这次是一个**恒绿**事故）：
  //   上一版用 body.match(...) —— 而 match 只返回【第一个】匹配。
  //   README 里第一个 N/M 是「34 / 50.7」（合法），于是 isCount=false 通过，
  //   而它【再也不会看后面的】——包括临时插进去的 239/239。
  //   ⇒ 它变成了恒绿判据。**而那是我先用探针验它会不会红，才发现的。**
  //   ★ 教训：遍历所有匹配（matchAll），而不是只看第一个。
  const body = t.replace(/!\[[^\]]*\]\([^)]*\)/g, '');   // 去掉 badge
  const hits = [...body.matchAll(/\b(\d{2,4})\s*\/\s*(\d{2,4})\b/g)]
    .filter(x => x[1] === x[2]);
  assert.equal(hits.length, 0,
    '★ 正文里出现了手写的 N/N 计数「' + (hits[0] && hits[0][0]) + '」—— ' +
    '手写的数字必然过期；应写成"全部通过"或指向 CI badge');
});
